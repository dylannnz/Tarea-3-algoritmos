    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
    String nombre = txtNombreA.getText().trim();
    String pais = txtPaisA.getText().trim();
    String oyentesTexto = txtOyentesA.getText().trim();

    if (nombre.isEmpty() || pais.isEmpty() || oyentesTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Completá todos los datos del artista.");
        return;
    }

    try {
        int oyentes = Integer.parseInt(oyentesTexto);

        if (oyentes < 0) {
            JOptionPane.showMessageDialog(this, "Los oyentes no pueden ser negativos.");
            return;
        }

        Artista artista = new Artista();
        artista.nombre = nombre;
        artista.paisOrigen = pais;
        artista.oyentesMensuales = oyentes;

        taResultados.append("=== ARTISTA CREADO ===\n");
        taResultados.append("Nombre: " + artista.nombre + "\n");
        taResultados.append("País de origen: " + artista.paisOrigen + "\n");
        taResultados.append("Oyentes mensuales: " + artista.oyentesMensuales + "\n\n");

        txtNombreA.setText("");
        txtPaisA.setText("");
        txtOyentesA.setText("");
        txtNombreA.requestFocus();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Los oyentes deben ser un número entero (sin comas ni puntos).");
    }
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
    String titulo = txtTituloC.getText().trim();
    String interprete = txtInterpreteC.getText().trim();
    String duracionTexto = txtDuracionC.getText().trim();
    String genero = txtGeneroC.getText().trim();

    if (titulo.isEmpty() || interprete.isEmpty() || duracionTexto.isEmpty() || genero.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Completá todos los datos de la canción.");
        return;
    }

    try {
        int duracion = Integer.parseInt(duracionTexto);

        if (duracion <= 0) {
            JOptionPane.showMessageDialog(this, "La duración debe ser mayor a 0 segundos.");
            return;
        }

        Cancion cancion = new Cancion();
        cancion.titulo = titulo;
        cancion.nombreArtista = interprete;
        cancion.duracionSegundos = duracion;
        cancion.genero = genero;

        int minutos = cancion.duracionSegundos / 60;
        int segundos = cancion.duracionSegundos % 60;

        taResultados.append("=== CANCIÓN CREADA ===\n");
        taResultados.append("Título: " + cancion.titulo + "\n");
        taResultados.append("Intérprete: " + cancion.nombreArtista + "\n");
        taResultados.append("Duración: " + cancion.duracionSegundos + " s ("
                + minutos + ":" + String.format("%02d", segundos) + ")\n");
        taResultados.append("Género: " + cancion.genero + "\n\n");

        txtTituloC.setText("");
        txtInterpreteC.setText("");
        txtDuracionC.setText("");
        txtGeneroC.setText("");
        txtTituloC.requestFocus();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "La duración debe ser un número entero de segundos.");
    }
    }//GEN-LAST:event_btnCrearCancionActionPerformed

