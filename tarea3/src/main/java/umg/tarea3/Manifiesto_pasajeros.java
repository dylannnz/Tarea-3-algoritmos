    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    if (indice >= 5) {
        JOptionPane.showMessageDialog(this, "Ya registraste los 5 pasajeros. Presiona Exportar Manifiesto.");
        return;
    }

    String nombre = txtPasajero.getText().trim();
    if (nombre.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribe el nombre del pasajero.");
        return;
    }

    pasajeros[indice] = nombre;
    tamanifiesto.append((indice + 1) + ". " + nombre + "\n");
    indice++;

    txtPasajero.setText("");
    txtPasajero.requestFocus();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
    if (indice < 5) {
        JOptionPane.showMessageDialog(this, "Faltan pasajeros. Llevás " + indice + " de 5.");
        return;
    }

    try (FileWriter fw = new FileWriter("temp/Dylan_manifiesto.txt")) {
        fw.write("Manifiesto Oficial de Vuelo\n");

        for (int i = 0; i < pasajeros.length; i++) {
            fw.write((i + 1) + ". " + pasajeros[i] + "\n");
        }

        JOptionPane.showMessageDialog(this, "Manifiesto exportado en la carpeta temp.");

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage());
    }
    }//GEN-LAST:event_btnExportarActionPerformed

