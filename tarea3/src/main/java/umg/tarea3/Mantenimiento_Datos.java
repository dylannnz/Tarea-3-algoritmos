    String ruta = "temp/Dylan_discos.csv";
    private static final java.util.logging.Logger logger = java.util.logging.Logger.getLogger(Mantenimiento_Datos.class.getName());

private void cargarDatos() {
    File archivo = new File(ruta);

    if (!archivo.exists()) {
        JOptionPane.showMessageDialog(this, "No se encontró " + ruta + ". Creá el archivo con 5 discos (Título,Año).");
        return;
    }

    total = 0;

    try (Scanner sc = new Scanner(archivo)) {
        while (sc.hasNextLine() && total < titulos.length) {
            String linea = sc.nextLine().trim();
            if (linea.isEmpty()) {
                continue;
            }
            String[] partes = linea.split(",");
            titulos[total] = partes[0].trim();
            anios[total] = Integer.parseInt(partes[1].trim());
            total++;
        }
    } catch (java.io.FileNotFoundException e) {
        JOptionPane.showMessageDialog(this, "No se pudo abrir el archivo.");
    } catch (NumberFormatException | ArrayIndexOutOfBoundsException e) {
        JOptionPane.showMessageDialog(this, "Hay una línea mal formada en discos.csv. Formato: Titulo,Año");
        total = 0;
    }
}

private int buscarIndice(String titulo) {
    for (int i = 0; i < total; i++) {
        if (titulos[i].equalsIgnoreCase(titulo)) {
            return i;
        }
    }
    return -1;
}

private boolean guardarCsv() {

    try (FileWriter fw = new FileWriter(ruta, false)) {
        for (int i = 0; i < total; i++) {
            fw.write(titulos[i] + "," + anios[i] + "\n");
        }
        return true;
    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage());
        return false;
    }
}
    
