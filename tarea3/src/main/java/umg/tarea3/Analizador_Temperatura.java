    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    if (indice >= 6) {
        JOptionPane.showMessageDialog(this, "Ya registraste los 6 Dias. Presiona Exportar");
        return;
    }

    double temperatura = Integer.parseInt(txtTemperatura.getText().trim());

    temperaturas[indice] = temperatura;
    indice++;

    txtTemperatura.setText("");
    txtTemperatura.requestFocus();
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
    if (indice < 6) {
        JOptionPane.showMessageDialog(this, "Faltan dias. Llevás " + indice + " de 6.");
        return;
    }

    try (FileWriter fw = new FileWriter("temp/Dylan_temperaturas.txt")) {
        for (int i = 0; i < temperaturas.length; i++) {
            fw.write(temperaturas[i] + "\n");
        }

        JOptionPane.showMessageDialog(this, "Reporte exportado en la carpeta temp.");

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error al escribir el archivo: " + e.getMessage());
    }
    }//GEN-LAST:event_btnExportarActionPerformed

    private void btnCargarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarActionPerformed
    File archivo = new File(ruta);

    if (!archivo.exists()) {
        JOptionPane.showMessageDialog(this, "No se encontró el archivo " + ruta);
        return;
    }

    indice = 0;

    try (Scanner sc = new Scanner(archivo)) {
        while (sc.hasNextLine() && indice < temperaturas.length) {
            String linea = sc.nextLine().trim();
            if (linea.isEmpty()) {
                continue;
            }
            temperaturas[indice] = Double.parseDouble(linea);
            indice++;
        }

        if (indice < temperaturas.length) {
            JOptionPane.showMessageDialog(this, "El archivo solo tiene " + indice + " registros. Se necesitan 6.");
            return;
        }

        JOptionPane.showMessageDialog(this, "Datos cargados en memoria.");

    } catch (FileNotFoundException e) {
        JOptionPane.showMessageDialog(this, "No se pudo abrir el archivo.");
    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Hay una línea del archivo que no es un número válido.");
        indice = 0;
    }
    }//GEN-LAST:event_btnCargarActionPerformed

    private void btncalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btncalcularActionPerformed
    // 1. Solo si ya se cargaron los 6 datos
    if (indice < 6) {
        JOptionPane.showMessageDialog(this, "Primero presioná Cargar Datos.");
        return;
    }

    // 2. Recorrer el arreglo
    double suma = 0;
    int calidos = 0;
    int frescos = 0;

    for (int i = 0; i < temperaturas.length; i++) {
        suma += temperaturas[i];
        if (temperaturas[i] >= 25.0) {
            calidos++;
        } else {
            frescos++;
        }
    }

    double promedio = suma / temperaturas.length;

    taReporte.setText("Análisis Climático\n"
            + "------------------\n"
            + "Promedio de Temperatura: " + promedio + "\n"
            + "Días Cálidos (>= 25°): " + calidos + "\n"
            + "Días Frescos (< 25°): " + frescos);
    }//GEN-LAST:event_btncalcularActionPerformed

