    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
    if (total >= titulos.length) {
        JOptionPane.showMessageDialog(this, "Ya tenés los 5 discos. Presioná Exportar Registro.");
        return;
    }

    String[] partes = txtDisco.getText().trim().split(",");

    if (partes.length != 2) {
        JOptionPane.showMessageDialog(this, "Usá el formato Título,Año (ej. Thriller,1982).");
        return;
    }

    String titulo = partes[0].trim();

    if (titulo.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribí un título antes de la coma.");
        return;
    }
    if (buscarIndice(titulo) != -1) {
        JOptionPane.showMessageDialog(this, "Ese disco ya está registrado.");
        return;
    }

    try {
        int anio = Integer.parseInt(partes[1].trim());

        if (anio < 1900 || anio > 2100) {
            JOptionPane.showMessageDialog(this, "Ingresá un año entre 1900 y 2100.");
            return;
        }

        titulos[total] = titulo;
        anios[total] = anio;
        total++;

        txtDisco.setText("");
        txtDisco.requestFocus();
        JOptionPane.showMessageDialog(this, "Disco " + total + " de 5 agregado. Presioná Exportar Registro al terminar.");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número entero.");
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
    if (total < titulos.length) {
        JOptionPane.showMessageDialog(this, "Faltan discos. Llevás " + total + " de 5.");
        return;
    }

    if (guardarCsv()) {
        JOptionPane.showMessageDialog(this, "Archivo creado en la carpeta temp.");
    }
    }//GEN-LAST:event_btnExportarActionPerformed

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        String titulo = txtBuscar.getText().trim();

    if (titulo.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Escribí el nombre del álbum.");
        return;
    }

    int pos = buscarIndice(titulo);

    if (pos == -1) {
        taDisco.setText("Álbum no encontrado.");
        return;
    }

    taDisco.setText(titulos[pos] + " - Año: " + anios[pos]);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
    int pos = buscarIndice(txtBuscar.getText().trim());

    if (pos == -1) {
        JOptionPane.showMessageDialog(this, "Primero escribí un álbum que exista en Buscar disco.");
        return;
    }

    try {
        int nuevo = Integer.parseInt(txtAnioNuevo.getText().trim());

        if (nuevo < 1900 || nuevo > 2100) {
            JOptionPane.showMessageDialog(this, "Ingresá un año entre 1900 y 2100.");
            return;
        }

        anios[pos] = nuevo;

        if (guardarCsv()) {
            taDisco.setText(titulos[pos] + " - Año: " + anios[pos]);
            txtAnioNuevo.setText("");
            JOptionPane.showMessageDialog(this, "Registro actualizado y discos.csv sobrescrito.");
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número entero.");
    }
    }//GEN-LAST:event_btnActualizarActionPerformed

