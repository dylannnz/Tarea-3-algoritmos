    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed

    String titulo = txtTitulo.getText().trim();
    String consola = txtConsola.getText().trim();
    String anioTexto = txtAnio.getText().trim();

    if (titulo.isEmpty() || consola.isEmpty() || anioTexto.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Completá título, consola y año.");
        return;
    }

    try {
        int anio = Integer.parseInt(anioTexto);

        if (anio < 1950 || anio > 2100) {
            JOptionPane.showMessageDialog(this, "Ingresá un año entre 1950 y 2100.");
            return;
        }

        videojuego juego = new videojuego(titulo, consola, anio);
        catalogo.add(juego);

        txtTitulo.setText("");
        txtConsola.setText("");
        txtAnio.setText("");
        txtTitulo.requestFocus();

        JOptionPane.showMessageDialog(this, "Juego agregado. Total en catálogo: " + catalogo.size());

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El año debe ser un número entero.");
    }
    }//GEN-LAST:event_btnAgregarActionPerformed

    private void btnMostrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMostrarActionPerformed
    taCatalogo.setText("");
    taCatalogo.append("=== CATÁLOGO DE VIDEOJUEGOS ===\n");

    for (int i = 0; i < catalogo.size(); i++) {
        videojuego v = catalogo.get(i);
        taCatalogo.append((i + 1) + ". " + v.titulo + " | " + v.consola + " | " + v.anioLanzamiento + "\n");
    }

    taCatalogo.append("\nTotal de juegos registrados: " + catalogo.size());
    }//GEN-LAST:event_btnMostrarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed

    if (catalogo.size() > 0) {
        videojuego eliminado = catalogo.remove(catalogo.size() - 1);

        JOptionPane.showMessageDialog(this, "Se eliminó: " + eliminado.titulo + ". Quedan " + catalogo.size() + " juegos.");
    } else {
        JOptionPane.showMessageDialog(this, "El catálogo está vacío, no hay nada que eliminar.");
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

